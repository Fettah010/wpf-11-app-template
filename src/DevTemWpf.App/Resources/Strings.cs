    /// already saw German (see 1.3.0 report). Language changes still require
    /// a restart (documented). Tests set this explicitly; never rely on
    /// ambient thread culture here.
    /// </summary>
    public static CultureInfo? OverrideCulture { get; set; }

    public static string Get(string key, CultureInfo? culture = null)
        => Manager.GetString(key, culture ?? OverrideCulture ?? CultureInfo.CurrentUICulture) ?? $"!{key}!";

